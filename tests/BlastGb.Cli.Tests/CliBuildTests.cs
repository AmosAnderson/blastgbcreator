using System.Text;
using System.Text.Json.Nodes;
using BlastGb.Cli;
using BlastGb.Core;

namespace BlastGb.Cli.Tests;

public sealed class NativeRgbdsFactAttribute : FactAttribute
{
    public NativeRgbdsFactAttribute()
    {
        if (string.IsNullOrEmpty(Environment.GetEnvironmentVariable("RGBDS_BIN")))
            Skip = "Set RGBDS_BIN to enable actual RGBDS integration tests.";
    }
}

public sealed class CliBuildTests : IDisposable
{
    private readonly string directory = Path.Combine(Path.GetTempPath(), "blast C# RGBDS #$ " + Guid.NewGuid().ToString("N"));
    public CliBuildTests() => Directory.CreateDirectory(directory);
    public void Dispose() => Directory.Delete(directory, true);
    private string FileAt(string name) => Path.Combine(directory, name);
    private static string Error((int Status, JsonNode Json) result) => result.Json["error"]!["code"]!.GetValue<string>();

    [NativeRgbdsFact]
    public async Task ImportedRomRebuildsExactlyIncludingPartialBanks()
    {
        var original = new byte[65536];
        GameCompiler.Build(GameCompiler.CreateStarterSpec()).Rom.CopyTo(original, 0);
        for (var index = 32768; index < original.Length; index++) original[index] = (byte)((index * 73 + 19) & 255);
        foreach (var length in new[] { 16384, 32767, 32768, 49151, 65536 })
        {
            var rom = original[..length];
            var input = FileAt($"partial-{length}.gb");
            File.WriteAllBytes(input, rom);
            var project = FileAt($"mod-{length}");
            Assert.Equal(0, (await CliTests.Invoke("project", "import", input, project)).Status);
            var built = await CliTests.Invoke("build", project);
            Assert.True(built.Status == 0, built.Json.ToJsonString());
            Assert.Equal(rom, File.ReadAllBytes(built.Json["data"]!["output"]!.GetValue<string>()));
            Assert.Contains("File generated by rgblink", File.ReadAllText(built.Json["data"]!["symbols"]!.GetValue<string>()));
            Assert.Contains("ROM0", File.ReadAllText(built.Json["data"]!["map"]!.GetValue<string>()));
            Assert.Equal(rom, File.ReadAllBytes(input));
        }
    }

    [NativeRgbdsFact]
    public async Task ExtraAssembledBankCannotBeSilentlyTrimmedOrReplacePreviousArtifacts()
    {
        var input = FileAt("original.gb");
        File.WriteAllBytes(input, GameCompiler.Build(GameCompiler.CreateStarterSpec()).Rom);
        var project = FileAt("mod");
        await CliTests.Invoke("import", input, project);
        var built = await CliTests.Invoke("build", project);
        Assert.True(built.Status == 0, built.Json.ToJsonString());
        var artifacts = new[] { "output", "symbols", "map" }.Select(key => built.Json["data"]![key]!.GetValue<string>()).ToArray();
        var retained = artifacts.Select(File.ReadAllBytes).ToArray();
        File.AppendAllText(Path.Combine(project, "source", "main.asm"), "\nSECTION \"Extra bank\", ROMX[$4000], BANK[2]\nExtraContent: db $7f\n");
        var rejected = await CliTests.Invoke("build", project, "--overwrite");
        Assert.Equal(1, rejected.Status);
        Assert.Equal("BUILD_FAILED", Error(rejected));
        Assert.Contains("32768", rejected.Json["error"]!["message"]!.GetValue<string>());
        for (var index = 0; index < artifacts.Length; index++) Assert.Equal(retained[index], File.ReadAllBytes(artifacts[index]));
    }

    [NativeRgbdsFact]
    public async Task AssemblyDependencyAndBinaryCollisionsProtectEveryInputAndArtifact()
    {
        foreach (var collision in new[] { "include", "binary", "symbols", "map" })
        {
            var cwd = FileAt(collision);
            Directory.CreateDirectory(Path.Combine(cwd, "nested"));
            var source = Path.Combine(cwd, "main.asm");
            var first = Path.Combine(cwd, "nested", "first.inc");
            var dependencyName = collision == "symbols" ? "game.sym" : collision == "map" ? "game.map" : "nested/code.inc";
            var dependency = Path.Combine(cwd, dependencyName);
            var binary = Path.Combine(cwd, "asset $ #.bin");
            File.WriteAllText(source, "INCLUDE \"nested/first.inc\"\n");
            File.WriteAllText(first, $"INCLUDE \"{dependencyName}\"\n");
            File.WriteAllText(dependency, "SECTION \"ROM\", ROM0[$0000]\nINCBIN \"asset $ #.bin\"\nds $4000 - @, 0\n");
            File.WriteAllBytes(binary, [1, 2, 3, 4]);
            var output = collision == "include" ? dependency : collision == "binary" ? binary : Path.Combine(cwd, "game.gb");
            var artifacts = new[] { output, Path.ChangeExtension(output, ".sym"), Path.ChangeExtension(output, ".map") };
            foreach (var artifact in artifacts) if (!File.Exists(artifact)) File.WriteAllText(artifact, "previous artifact: " + artifact);
            var protectedPaths = new[] { source, first, dependency, binary }.Concat(artifacts).Distinct().ToArray();
            var before = protectedPaths.Select(File.ReadAllBytes).ToArray();
            var rejected = await CliTests.Invoke("asm", "compile", source, "--output", output, "--overwrite");
            Assert.Equal(1, rejected.Status);
            Assert.Equal("UNSAFE_OUTPUT", Error(rejected));
            for (var index = 0; index < protectedPaths.Length; index++) Assert.Equal(before[index], File.ReadAllBytes(protectedPaths[index]));
        }
    }

    [NativeRgbdsFact]
    public async Task AssemblesNestedBinaryDependenciesWithoutTouchingInputs()
    {
        var source = FileAt("main.asm");
        var dependency = FileAt("code $ #.inc");
        var binary = FileAt("asset $ #.bin");
        File.WriteAllText(source, "INCLUDE \"code $ #.inc\"\n");
        File.WriteAllText(dependency, "SECTION \"ROM\", ROM0[$0000]\nINCBIN \"asset $ #.bin\"\nds $4000 - @, 0\n");
        File.WriteAllBytes(binary, [1, 2, 3, 4]);
        var before = new[] { source, dependency, binary }.Select(File.ReadAllBytes).ToArray();
        var built = await CliTests.Invoke("asm", "compile", source);
        Assert.True(built.Status == 0, built.Json.ToJsonString());
        Assert.Equal([1, 2, 3, 4], File.ReadAllBytes(built.Json["data"]!["output"]!.GetValue<string>())[..4]);
        var after = new[] { source, dependency, binary }.Select(File.ReadAllBytes).ToArray();
        for (var index = 0; index < before.Length; index++) Assert.Equal(before[index], after[index]);
    }

    [NativeRgbdsFact]
    public async Task FilesystemAliasesCannotClobberRomWithSidecarEvenWithoutOverwrite()
    {
        foreach (var extension in new[] { "SYM", "MAP", "SyM", "MaP" })
            foreach (var overwrite in new[] { false, true })
            {
                var cwd = FileAt(extension + overwrite);
                Directory.CreateDirectory(cwd);
                var source = Path.Combine(cwd, "main.asm");
                var contents = RomTools.ExportDisassembly(GameCompiler.Build(GameCompiler.CreateStarterSpec()).Rom);
                File.WriteAllText(source, contents);
                File.WriteAllText(Path.Combine(cwd, "case-probe"), "probe");
                var insensitive = File.Exists(Path.Combine(cwd, "CASE-PROBE"));
                File.Delete(Path.Combine(cwd, "case-probe"));
                var output = Path.Combine(cwd, "game." + extension);
                var artifacts = new[] { output, Path.Combine(cwd, "game.sym"), Path.Combine(cwd, "game.map") };
                if (overwrite) foreach (var artifact in artifacts) if (!File.Exists(artifact)) File.WriteAllText(artifact, "previous artifact: " + artifact);
                var before = artifacts.Select(path => File.Exists(path) ? File.ReadAllBytes(path) : null).ToArray();
                var built = await CliTests.Invoke(["asm", "compile", source, "--output", output, .. overwrite ? new[] { "--overwrite" } : []]);
                if (insensitive)
                {
                    Assert.Equal(1, built.Status);
                    Assert.Equal("UNSAFE_OUTPUT", Error(built));
                    for (var index = 0; index < artifacts.Length; index++) Assert.Equal(before[index], File.Exists(artifacts[index]) ? File.ReadAllBytes(artifacts[index]) : null);
                }
                else
                {
                    Assert.True(built.Status == 0, built.Json.ToJsonString());
                    Assert.Equal(built.Json["data"]!["size"]!.GetValue<int>(), File.ReadAllBytes(output).Length);
                }
                Assert.Equal(contents, File.ReadAllText(source));
                Assert.DoesNotContain(Directory.EnumerateFiles(cwd), path => path.EndsWith(".tmp", StringComparison.Ordinal) || path.EndsWith(".bak", StringComparison.Ordinal));
            }
    }


    [NativeRgbdsFact]
    public async Task UnicodeNormalizationAliasCannotReplaceAssemblyInput()
    {
        var source = FileAt("café.asm");
        var alias = FileAt("cafe\u0301.asm");
        const string original = "SECTION \"ROM\", ROM0[0]\nds $4000, 0\n";
        File.WriteAllText(source, original);
        var aliases = File.Exists(alias);
        var built = await CliTests.Invoke("asm", "compile", source, "--output", alias, "--overwrite");
        if (aliases)
        {
            Assert.Equal(1, built.Status);
            Assert.Equal("UNSAFE_OUTPUT", Error(built));
        }
        else
        {
            Assert.True(built.Status == 0, built.Json.ToJsonString());
            Assert.Equal(16384, File.ReadAllBytes(alias).Length);
        }
        Assert.Equal(original, File.ReadAllText(source));
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void UnicodeNormalizationOutputAliasesAreRejectedBeforeCommit(bool overwrite)
    {
        var first = FileAt("café.gb");
        var second = FileAt("cafe\u0301.gb");
        File.WriteAllBytes(first, [7]);
        var aliases = File.Exists(second);
        File.Delete(first);
        if (overwrite)
        {
            File.WriteAllBytes(first, [7]);
            if (!aliases) File.WriteAllBytes(second, [8]);
        }
        FileOperations.Artifact[] artifacts = [new(first, new byte[] { 1 }), new(second, new byte[] { 2 })];
        if (aliases)
        {
            Assert.Equal("UNSAFE_OUTPUT", Assert.Throws<CliException>(() => FileOperations.AtomicWriteBatch(artifacts, overwrite)).Code);
            if (overwrite) Assert.Equal(new byte[] { 7 }, File.ReadAllBytes(first));
            else Assert.False(File.Exists(first));
        }
        else
        {
            FileOperations.AtomicWriteBatch(artifacts, overwrite);
            Assert.Equal(new byte[] { 1 }, File.ReadAllBytes(first));
            Assert.Equal(new byte[] { 2 }, File.ReadAllBytes(second));
        }
        Assert.DoesNotContain(Directory.EnumerateFiles(directory), path => path.EndsWith(".tmp", StringComparison.Ordinal) || path.EndsWith(".bak", StringComparison.Ordinal));
    }

    [Fact]
    public void CommitRaceWithoutOverwritePreservesUnexpectedDestinationAndRollsBackEarlierFile()
    {
        var first = new FileOperations.StagedArtifact(FileAt("first.gb"), FileAt("first.tmp"), FileAt("first.bak"));
        var second = new FileOperations.StagedArtifact(FileAt("second.sym"), FileAt("second.tmp"), FileAt("second.bak"));
        File.WriteAllBytes(first.Temporary, [1]);
        File.WriteAllBytes(second.Temporary, [2]);
        // This file represents another process creating the destination after preflight.
        File.WriteAllBytes(second.Path, [99]);
        Assert.Throws<IOException>(() => FileOperations.CommitStagedArtifacts([first, second], false));
        Assert.False(File.Exists(first.Path));
        Assert.Equal(new byte[] { 99 }, File.ReadAllBytes(second.Path));
        Assert.False(File.Exists(first.Backup));
        Assert.False(File.Exists(second.Backup));
    }

    [Fact]
    public void FailedLaterCommitRestoresEveryPreviousArtifact()
    {
        var first = new FileOperations.StagedArtifact(FileAt("first.gb"), FileAt("first.tmp"), FileAt("first.bak"));
        var second = new FileOperations.StagedArtifact(FileAt("second.sym"), FileAt("missing.tmp"), FileAt("second.bak"));
        File.WriteAllBytes(first.Path, [11]);
        File.WriteAllBytes(second.Path, [22]);
        File.WriteAllBytes(first.Temporary, [1]);
        Assert.Throws<FileNotFoundException>(() => FileOperations.CommitStagedArtifacts([first, second], true));
        Assert.Equal(new byte[] { 11 }, File.ReadAllBytes(first.Path));
        Assert.Equal(new byte[] { 22 }, File.ReadAllBytes(second.Path));
        Assert.False(File.Exists(first.Backup));
        Assert.False(File.Exists(second.Backup));
    }

    [Fact]
    public void DependencyReportsPreserveLiteralSpecialCharactersAndRejectAmbiguity()
    {
        var source = FileAt("main.asm");
        File.WriteAllText(source, "");
        var names = new List<string> { "space x.inc", "hash#x.inc", "dollar$x.inc" };
        if (!OperatingSystem.IsWindows()) names.AddRange(["back\\slash.inc", "tab\tx.inc", "colon:x.inc", " leading and trailing "]);
        foreach (var name in names) File.WriteAllText(FileAt(name), "");
        var target = AssemblyDependencies.CreateTarget();
        string Report(params string[] paths) => string.Concat(new[] { source }.Concat(paths).Select(path => $"{target}: {path}\n"));
        var dependencies = AssemblyDependencies.Parse(Encoding.UTF8.GetBytes(Report([.. names, names[0]])), target, directory, source);
        Assert.Equal(new[] { source }.Concat(names.Select(FileAt)), dependencies);
        Directory.CreateDirectory(FileAt("directory.inc"));
        foreach (var text in new[] { "", Report().TrimEnd(), Report("missing.inc"), Report("directory.inc"), Report() + target + ": \n", Report() + "different-target: other.inc\n", target + ": other.inc\n", Report() + target + ": other.inc\0\n" })
            Assert.Contains("Cannot confirm assembler inputs", Assert.Throws<CliException>(() => AssemblyDependencies.Parse(Encoding.UTF8.GetBytes(text), target, directory, source)).Message);
        Assert.Throws<CliException>(() => AssemblyDependencies.Parse(Encoding.UTF8.GetBytes(Report()), "unsafe\ntarget", directory, source));
        File.WriteAllText(FileAt("\ufffd.inc"), "");
        var invalid = Encoding.UTF8.GetBytes(Report() + target + ": ").Concat(new byte[] { 0xff }).Concat(Encoding.UTF8.GetBytes(".inc\n")).ToArray();
        Assert.Contains("not valid UTF-8", Assert.Throws<CliException>(() => AssemblyDependencies.Parse(invalid, target, directory, source)).Message);
    }

    [Fact]
    public void RomExtentRequiresCompleteProofOfPadding()
    {
        CliApplication.ValidateRomExtent("ROM0 bank #0:\n  SECTION: $0000-$3fff ($4000 bytes)\n", 16384);
        Assert.Throws<CliException>(() => CliApplication.ValidateRomExtent("ROM0 bank #0:\n  SECTION: malformed\n", 32768));
        Assert.Throws<CliException>(() => CliApplication.ValidateRomExtent("ROM0 bank #0:\n  SECTION: $0000-$3fff ($4000 bytes)\nROMX bank #2:\n  SECTION: $4000 ($1 byte)\n", 32768));
        Assert.Throws<CliException>(() => CliApplication.ValidateRomExtent("", 32768));
    }

    [Fact]
    public void AtomicBatchPreflightPreservesEarlierArtifactsAndCleansStagingOnFailure()
    {
        var first = FileAt("first.gb");
        File.WriteAllBytes(first, [1, 2, 3]);
        var obstructed = FileAt("second.sym");
        Directory.CreateDirectory(obstructed);
        Assert.Throws<CliException>(() => FileOperations.AtomicWriteBatch([new(first, new byte[] { 9 }), new(obstructed, "symbols")], true));
        Assert.Equal([1, 2, 3], File.ReadAllBytes(first));
        Assert.DoesNotContain(Directory.EnumerateFiles(directory), path => path.EndsWith(".tmp", StringComparison.Ordinal) || path.EndsWith(".bak", StringComparison.Ordinal));
    }
