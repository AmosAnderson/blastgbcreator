using BlastGb.Core;

namespace BlastGb.Core.Tests;

public sealed class RgbdsSymbolsTests
{
    [Fact]
    public void ParsesCommentsBankedLabelsAndNonRomSymbolsWithoutGuessing()
    {
        var table = RgbdsSymbols.Parse("\ufeff; File generated by rgblink\r\n00:0150 Entry\r\n01:4000 Main.loop ; comment\n01:4000 Alias\n01ff:7FFF Last\n00:c000 State\n00:4000 Ambiguous\n01:0010 OtherSpace\n\n");
        Assert.Equal(7, table.Symbols.Count);
        Assert.Equal(0x150, table.GetByName("Entry").RomOffset);
        Assert.Equal(0x4000, table.GetByName("Main.loop").RomOffset);
        Assert.Equal(0x7fffff, table.GetByName("Last").RomOffset);
        Assert.Null(table.GetByName("State").RomOffset);
        Assert.Null(table.GetByName("Ambiguous").RomOffset);
        Assert.Null(table.GetByName("OtherSpace").RomOffset);
        Assert.Equal(new[] { "Main.loop", "Alias" }, table.FindByRomOffset(0x4000).Select(symbol => symbol.Name));
        Assert.False(table.TryGetByName("entry", out _));
        Assert.Throws<ArgumentException>(() => table.GetByName("entry"));
        Assert.Empty(RgbdsSymbols.Parse("; empty\n").Symbols);
    }

    [Fact]
    public void ExportedConstantsDoNotBecomeMappedAddressSymbols()
    {
        var table = RgbdsSymbols.Parse("00 Zero\n01 One\n80000000 Minimum\nffffffff Negative\nc000 RamConstant ; not a RAM label\n00:0150 Entry\n00:c000 State\n");
        Assert.Equal(new[] { "Entry", "State" }, table.Symbols.Select(symbol => symbol.Name));
        Assert.Equal(0x150, table.GetByName("Entry").RomOffset);
        foreach (string constant in new[] { "Zero", "One", "Minimum", "Negative", "RamConstant" })
        {
            Assert.False(table.TryGetByName(constant, out _));
            Assert.Throws<ArgumentException>(() => table.GetByName(constant));
        }
        Assert.Empty(RgbdsSymbols.Parse("ff OnlyConstant\n").Symbols);
    }

    [Theory]
    [InlineData("00:150 Entry")]
    [InlineData("0:0150 Entry")]
    [InlineData("gg:0150 Entry")]
    [InlineData("0200:4000 Entry")]
    [InlineData("00:10000 Entry")]
    [InlineData("00:0150")]
    [InlineData("00:0150 two names")]
    [InlineData("00:0150 Entry\n01:4000 Entry")]
    [InlineData("nothex Constant")]
    [InlineData("100000000 Constant")]
    [InlineData("-1 Constant")]
    [InlineData("01 two names")]
    [InlineData("01")]
    [InlineData("00 Constant\n01 Constant")]
    [InlineData("00:0150 Entry\nc000 Entry")]
    [InlineData("c000 Entry\n00:0150 Entry")]
    public void RejectsMalformedAndDuplicateRecords(string source) => Assert.Throws<ArgumentException>(() => RgbdsSymbols.Parse(source));

    [RgbdsFact]
    public void ParsesRealLinkerSymbolsAcrossRomAndRamSections()
    {
        using var rgbds = new RgbdsFixture();
        _ = rgbds.Assemble("""
            DEF Zero EQU 0
            DEF RamConstant EQU $c000
            DEF Negative EQU -1
            DEF Minimum EQU -2147483648
            DEF Maximum EQU $7fffffff
            EXPORT Zero, RamConstant, Negative, Minimum, Maximum
            SECTION "Entry", ROM0[$0100]
            Entry:: nop
            SECTION "Banked", ROMX[$4000], BANK[2]
            Banked:: ret
            SECTION "State", WRAM0[$c000]
            State:: ds 1
            """, out var symbols);
        var table = RgbdsSymbols.Parse(symbols);
        Assert.Equal(0x100, table.GetByName("Entry").RomOffset);
        Assert.Equal(0x8000, table.GetByName("Banked").RomOffset);
        Assert.Equal(2, table.GetByName("Banked").Bank);
        Assert.Equal(0xc000, table.GetByName("State").Address);
        Assert.Null(table.GetByName("State").RomOffset);
        Assert.Equal(3, table.Symbols.Count);
        Assert.Contains("c000 RamConstant", symbols);
        Assert.Contains("ffffffff Negative", symbols);
        Assert.Contains("80000000 Minimum", symbols);
        foreach (string constant in new[] { "Zero", "RamConstant", "Negative", "Minimum", "Maximum" })
            Assert.False(table.TryGetByName(constant, out _));
    }
}
