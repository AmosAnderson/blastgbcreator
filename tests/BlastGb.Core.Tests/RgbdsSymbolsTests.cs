using System.Globalization;
using BlastGb.Core;

namespace BlastGb.Core.Tests;

public sealed class RgbdsSymbolsTests
{
    [Fact]
    public void ParsesLabelsConstantsCommentsAndConservativeRomMappings()
    {
        var symbols = RgbdsSymbols.Parse("\ufeff; File generated by rgblink\r\n\r\n00:0150 Entry\r\n01:4000 BankOne\n1ff:7fff LastByte ; comment\n" +
            "00:4000 Ambiguous\n01:0150 SwitchedLowBank\n200:4000 TooLarge\n01:8000 Video\n02:a000 SaveRam\n00:c000 WorkRam\n00:ff80 HighRam\n" +
            "2a Answer\nffffffff Negative\n\t00:0151\tEntry.local\t\n");
        Assert.Equal(13, symbols.Count);
        Assert.Equal(0x150, symbols[0].RomOffset);
        Assert.Equal(0x4000, symbols[1].RomOffset);
        Assert.Equal(RomTools.MaxRomSize - 1, symbols[2].RomOffset);
        Assert.All(symbols.Skip(3).Take(7), symbol => Assert.Null(symbol.RomOffset));
        Assert.Equal("constant", symbols[10].Kind);
        Assert.Equal(42, symbols[10].ConstantValue);
        Assert.Null(symbols[10].Bank);
        Assert.Null(symbols[10].Address);
        Assert.Null(symbols[10].RomOffset);
        Assert.Equal(-1, symbols[11].ConstantValue);
        Assert.Equal("Entry.local", symbols[12].Name);
        Assert.Equal("label", symbols[12].Kind);
        Assert.Null(symbols[12].ConstantValue);
    }

    [Fact]
    public void NamesUseOrdinalMatchingAndDecodeUnicodeEscapes()
    {
        var symbols = RgbdsSymbols.Parse("00:0150 Entry\n00:0150 entry\n01:4000 Caf\\u00e9\\U0001f31f\n");
        Assert.Equal(["Entry", "entry", "Café🌟"], symbols.Select(symbol => symbol.Name).ToArray());
        Assert.Throws<FormatException>(() => RgbdsSymbols.Parse("00:0150 Entry\n01:4000 Entry\n"));
        Assert.Throws<FormatException>(() => RgbdsSymbols.Parse("00:0150 A\n00:0151 \\u0041\n"));
    }

    [Theory]
    [InlineData("00:0150")]
    [InlineData("00:0150 ")]
    [InlineData("00:0150 Two Names")]
    [InlineData("gg:0150 BadBank")]
    [InlineData("10000:0150 BadBank")]
    [InlineData("00:10000 BadAddress")]
    [InlineData("00:150 ShortAddress")]
    [InlineData("00:01x0 BadAddress")]
    [InlineData("100000000 OversizedConstant")]
    [InlineData("00:0150 Bad\\q")]
    [InlineData("00:0150 Bad\\ud800")]
    [InlineData("00:0150 Bad\\U00110000")]
    [InlineData("00:0150 Bad\\u0000")]
    public void MalformedRecordsFailClosed(string text) => Assert.Throws<FormatException>(() => RgbdsSymbols.Parse(text));

    [Fact]
    public void EnforcesNameByteAndFileBounds()
    {
        Assert.Single(RgbdsSymbols.Parse("00:0150 " + new string('x', RgbdsSymbols.MaxNameBytes)));
        Assert.Throws<FormatException>(() => RgbdsSymbols.Parse("00:0150 " + new string('x', RgbdsSymbols.MaxNameBytes + 1)));
        Assert.Throws<FormatException>(() => RgbdsSymbols.Parse("00:0150 " + new string('é', RgbdsSymbols.MaxNameBytes)));
        Assert.Throws<ArgumentException>(() => RgbdsSymbols.Parse(new string(' ', RgbdsSymbols.MaxFileBytes + 1)));
        Assert.Throws<ArgumentException>(() => RgbdsSymbols.Parse(new string('é', RgbdsSymbols.MaxFileBytes / 2 + 1)));
        Assert.ThrowsAny<ArgumentException>(() => RgbdsSymbols.Parse("00:0150 \ud800"));
    }

    [Fact]
    public void EnforcesSymbolCountAtThePublishedBoundary()
    {
        var text = string.Concat(Enumerable.Range(0, RgbdsSymbols.MaxSymbols).Select(index =>
            "00:0150 Symbol" + index.ToString(CultureInfo.InvariantCulture) + "\n"));
        Assert.Equal(RgbdsSymbols.MaxSymbols, RgbdsSymbols.Parse(text).Count);
        Assert.Throws<FormatException>(() => RgbdsSymbols.Parse(text + "00:0150 OneMore\n"));
    }

    [Fact]
    public void ParsesCommentsBankedLabelsAndNonRomSymbolsWithoutGuessing()
    {
        var table = RgbdsSymbols.Parse("\ufeff; File generated by rgblink\r\n00:0150 Entry\r\n01:4000 Main.loop ; comment\n01:4000 Alias\n01ff:7FFF Last\n00:c000 State\n00:4000 Ambiguous\n01:0010 OtherSpace\n\n");
        Assert.Equal(7, table.Symbols.Count);
        Assert.Equal(0x150, table.GetByName("Entry").RomOffset);
        Assert.Equal(0x4000, table.GetByName("Main.loop").RomOffset);
        Assert.Equal(0x7fffff, table.GetByName("Last").RomOffset);
        Assert.Null(table.GetByName("State").RomOffset);
        Assert.Null(table.GetByName("Ambiguous").RomOffset);
        Assert.Null(table.GetByName("OtherSpace").RomOffset);
        Assert.Equal(new[] { "Main.loop", "Alias" }, table.FindByRomOffset(0x4000).Select(symbol => symbol.Name));
        Assert.False(table.TryGetByName("entry", out _));
        Assert.Throws<ArgumentException>(() => table.GetByName("entry"));
        Assert.Empty(RgbdsSymbols.Parse("; empty\n").Symbols);
    }

    [Fact]
    public void ExportedConstantsDoNotBecomeMappedAddressSymbols()
    {
        var table = RgbdsSymbols.Parse("00 Zero\n01 One\n80000000 Minimum\nffffffff Negative\nc000 RamConstant ; not a RAM label\n00:0150 Entry\n00:c000 State\n");
        Assert.Equal(new[] { "Entry", "State" }, table.Symbols.Select(symbol => symbol.Name));
        Assert.Equal(0x150, table.GetByName("Entry").RomOffset);
        foreach (string constant in new[] { "Zero", "One", "Minimum", "Negative", "RamConstant" })
        {
            Assert.False(table.TryGetByName(constant, out _));
            Assert.Throws<ArgumentException>(() => table.GetByName(constant));
        }
        Assert.Empty(RgbdsSymbols.Parse("ff OnlyConstant\n").Symbols);
    }

    [Theory]
    [InlineData("00:150 Entry")]
    [InlineData("gg:0150 Entry")]
    [InlineData("00:10000 Entry")]
    [InlineData("00:0150")]
    [InlineData("00:0150 two names")]
    [InlineData("00:0150 Entry\n01:4000 Entry")]
    [InlineData("nothex Constant")]
    [InlineData("100000000 Constant")]
    [InlineData("-1 Constant")]
    [InlineData("01 two names")]
    [InlineData("01")]
    [InlineData("00 Constant\n01 Constant")]
    [InlineData("00:0150 Entry\nc000 Entry")]
    [InlineData("c000 Entry\n00:0150 Entry")]
    public void RejectsMalformedAndDuplicateRecords(string source) => Assert.Throws<FormatException>(() => RgbdsSymbols.Parse(source));

    [RgbdsFact]
    public void ParsesRealLinkerSymbolsAcrossRomAndRamSections()
    {
        using var rgbds = new RgbdsFixture();
        _ = rgbds.Assemble("""
            DEF Zero EQU 0
            DEF RamConstant EQU $c000
            DEF Negative EQU -1
            DEF Minimum EQU -2147483648
            DEF Maximum EQU $7fffffff
            EXPORT Zero, RamConstant, Negative, Minimum, Maximum
            SECTION "Entry", ROM0[$0100]
            Entry:: nop
            SECTION "Banked", ROMX[$4000], BANK[2]
            Banked:: ret
            SECTION "State", WRAM0[$c000]
            State:: ds 1
            """, out var symbols);
        var table = RgbdsSymbols.Parse(symbols);
        Assert.Equal(0x100, table.GetByName("Entry").RomOffset);
        Assert.Equal(0x8000, table.GetByName("Banked").RomOffset);
        Assert.Equal(2, table.GetByName("Banked").Bank);
        Assert.Equal(0xc000, table.GetByName("State").Address);
        Assert.Null(table.GetByName("State").RomOffset);
        Assert.Equal(3, table.Symbols.Count);
        Assert.Contains("c000 RamConstant", symbols);
        Assert.Contains("ffffffff Negative", symbols);
        Assert.Contains("80000000 Minimum", symbols);
        foreach (string constant in new[] { "Zero", "RamConstant", "Negative", "Minimum", "Maximum" })
            Assert.False(table.TryGetByName(constant, out _));
    }
}
